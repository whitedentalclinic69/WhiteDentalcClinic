create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Custom',
  description text not null,
  price numeric not null default 0 check (price >= 0),
  duration text not null default 'Custom session',
  media_type text not null default 'image'
    check (media_type in ('image', 'video')),
  image_url text,
  video_url text,
  created_at timestamptz not null default now()
);

alter table public.gallery_items enable row level security;

insert into storage.buckets (id, name, public, allowed_mime_types)
values ('gallery-media', 'gallery-media', true, array['image/*', 'video/*'])
on conflict (id) do update
set public = excluded.public,
    allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  service_name text not null,
  service_price numeric(10, 2) not null check (service_price >= 0),
  deposit_amount numeric(10, 2) not null check (deposit_amount >= 0),
  balance_amount numeric(10, 2) not null check (balance_amount >= 0),
  appointment_date date not null,
  appointment_time time not null,
  payment_method text not null check (payment_method in ('card', 'paypal')),
  tattoo_notes text,
  ticket_number text not null unique,
  booking_status text not null default 'pending'
    check (booking_status in ('pending', 'confirmed', 'attended')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'paid')),
  created_at timestamptz not null default now()
);

alter table public.bookings
  add column if not exists service_description text not null default '',
  add column if not exists booking_notes text,
  add column if not exists paid_at timestamptz,
  add column if not exists paypal_order_id text;

create index if not exists bookings_created_at_idx
  on public.bookings (created_at desc);

create unique index if not exists bookings_paypal_order_id_idx
  on public.bookings (paypal_order_id)
  where paypal_order_id is not null;

create table if not exists public.visitor_questions (
  id bigint generated by default as identity primary key,
  customer_name text,
  customer_email text not null,
  question_text text not null,
  created_at timestamptz not null default now()
);

alter table public.visitor_questions
  add column if not exists response text,
  add column if not exists answered_at timestamptz;

create index if not exists visitor_questions_created_at_idx
  on public.visitor_questions (created_at desc);

create table if not exists public.social_links (
  singleton boolean primary key default true check (singleton),
  links jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.visitor_questions enable row level security;
alter table public.social_links enable row level security;

revoke all on public.visitor_questions from anon, authenticated;
revoke all on public.social_links from anon, authenticated;

grant select, insert, update, delete on public.visitor_questions to service_role;
grant usage, select on sequence public.visitor_questions_id_seq to service_role;
grant select, insert, update on public.social_links to service_role;
